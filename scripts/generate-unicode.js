import { readFileSync, writeFileSync } from "node:fs";
import idContinue from "@unicode/unicode-17.0.0/Binary_Property/ID_Continue/code-points.mjs";
import idStart from "@unicode/unicode-17.0.0/Binary_Property/ID_Start/code-points.mjs";
import decimalDigits from "@unicode/unicode-17.0.0/General_Category/Decimal_Number/code-points.mjs";
import letters from "@unicode/unicode-17.0.0/General_Category/Letter/code-points.mjs";

const outputs = [
  {
    path: "../javascript/common/unicode.js",
    classes: { unicodeIdStart: idStart, unicodeIdContinue: idContinue },
  },
  {
    path: "../pcre2/unicode.js",
    classes: { unicodeLetter: letters, unicodeDecimalDigit: decimalDigits },
  },
];

function characterClass(codePoints) {
  const ranges = [];
  for (const codePoint of codePoints.toSorted((left, right) => left - right)) {
    const previous = ranges.at(-1);
    if (previous && codePoint === previous[1] + 1) previous[1] = codePoint;
    else ranges.push([codePoint, codePoint]);
  }
  const codePointEscape = (value) => `\\u{${value.toString(16)}}`;
  return `[${ranges
    .map(([first, last]) =>
      first === last
        ? codePointEscape(first)
        : `${codePointEscape(first)}-${codePointEscape(last)}`,
    )
    .join("")}]`;
}

function generateUnicode(classes) {
  return [
    "// Generated by scripts/generate-unicode.js; do not edit.",
    "// Unicode data: @unicode/unicode-17.0.0; notice: LICENSE-UNICODE.",
    ...Object.entries(classes).flatMap(([name, codePoints]) => [
      `export const ${name} =`,
      `  ${JSON.stringify(characterClass(codePoints))};`,
    ]),
    "",
  ].join("\n");
}

function main(arguments_) {
  if (
    arguments_.length > 1 ||
    (arguments_.length === 1 && arguments_[0] !== "--check")
  ) {
    throw new Error("Usage: node scripts/generate-unicode.js [--check]");
  }
  for (const { path, classes } of outputs) {
    const outputPath = new URL(path, import.meta.url);
    const generated = generateUnicode(classes);
    if (arguments_.length === 0) {
      writeFileSync(outputPath, generated);
      continue;
    }
    let actual;
    try {
      actual = readFileSync(outputPath, "utf8");
    } catch (error) {
      if (
        !(error instanceof Error && "code" in error && error.code === "ENOENT")
      )
        throw error;
    }
    if (actual !== generated) {
      throw new Error(
        `${path}: generated Unicode classes are stale or missing; run node scripts/generate-unicode.js`,
      );
    }
  }
  return 0;
}

try {
  process.exitCode = main(process.argv.slice(2));
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
